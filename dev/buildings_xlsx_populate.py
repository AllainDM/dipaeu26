# Алиасы: ключ = название в RESOURCE_DATA, значение = название в xlsx
NAME_ALIASES = {
    "Кам/стена": "Каменная стена",
}


def main():
    wb = openpyxl.load_workbook('dev/buildings.xlsx')
    ws = wb.active

    # Добавляем заголовок колонки 14
    COL_RES = 14  # 0-indexed, Excel column 15
    ws.cell(row=1, column=COL_RES + 1, value='Ресурсы на постройку')

    matched = 0
    not_found = []

    for row in ws.iter_rows(min_row=2, values_only=False):
        name_cell = row[2]  # колонка C (0-indexed: 2) — Постройка
        name = str(name_cell.value).strip() if name_cell.value else ''
        if not name:
            continue

        # Прямое совпадение
        if name in RESOURCE_DATA:
            ws.cell(row=name_cell.row, column=COL_RES + 1, value=RESOURCE_DATA[name])
            matched += 1
        else:
            not_found.append(name)

    # Пробуем алиасы для не найденных
    for name in not_found[:]:
        xlsx_name = name
        for js_key, xlsx_key in NAME_ALIASES.items():
            if name == xlsx_key:
                # Применяем ресурс js_key к этой строке xlsx
                for row in ws.iter_rows(min_row=2, values_only=False):
                    n = str(row[2].value).strip() if row[2].value else ''
                    if n == name:
                        ws.cell(row=row[0].row, column=COL_RES + 1, value=RESOURCE_DATA[js_key])
                        matched += 1
                        not_found.remove(name)
                        break

    wb.save('dev/buildings.xlsx')

    # Отчёт
    print(f'Сопоставлено: {matched}')
    if not_found:
        print(f'Не найдены в RESOURCE_DATA ({len(not_found)}):')
        for n in sorted(set(not_found)):
            print(f'  - {n}')

    js_only = set(RESOURCE_DATA.keys()) - set(NAME_ALIASES.keys())
    xlsx_names = set()
    for row in ws.iter_rows(min_row=2, values_only=True):
        if row[2]:
            xlsx_names.add(str(row[2]).strip())
    js_only -= xlsx_names
    if js_only:
        print(f'Есть в справочнике, но нет в xlsx ({len(js_only)}):')
        for n in sorted(js_only):
            print(f'  - {n}')


if __name__ == '__main__':
    main()